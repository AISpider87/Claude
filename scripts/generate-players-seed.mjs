#!/usr/bin/env node
// Generates supabase/seed/players.sql from the real quotations fixture so the
// local database starts with a realistic listone. Dev only; production data
// comes from the admin import flow.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import ExcelJS from "exceljs";

const ROOT = path.resolve(new URL(".", import.meta.url).pathname, "..");
const FIXTURE = path.join(ROOT, "fixtures/Quotazioni_Fantacalcio_Stagione_2026_27.xlsx");
const OUT = path.join(ROOT, "supabase/seed/players.sql");

const COLS = {
  id: "id",
  r: "role_classic",
  rm: "role_mantra",
  nome: "name",
  squadra: "team",
  qta: "qt_a",
  qti: "qt_i",
  diff: "diff",
  qtam: "qt_a_m",
  qtim: "qt_i_m",
  diffm: "diff_m",
  fvm: "fvm",
  fvmm: "fvm_m",
};

const text = (v) =>
  (v == null
    ? ""
    : typeof v === "object" && v.richText
      ? v.richText.map((r) => r.text).join("")
      : String(v)
  ).trim();
const norm = (v) =>
  text(v)
    .toLowerCase()
    .replace(/[.\s_-]/g, "");
const sql = (v) =>
  v == null || v === ""
    ? "null"
    : typeof v === "number"
      ? String(v)
      : `'${String(v).replace(/'/g, "''")}'`;
const int = (v) => (text(v) === "" ? null : Math.round(Number(text(v))));

function readSheet(ws) {
  let header = null;
  const rows = [];
  ws.eachRow((row) => {
    const values = row.values;
    if (!header) {
      const normalized = values.map(norm);
      if (normalized.includes("nome") && normalized.includes("squadra")) {
        header = normalized.map((h) => COLS[h] ?? null);
      }
      return;
    }
    const rec = {};
    header.forEach((key, idx) => {
      if (key) rec[key] = values[idx];
    });
    const id = int(rec.id);
    if (!id) return;
    rows.push({
      id,
      name: text(rec.name),
      team: text(rec.team),
      role_classic: text(rec.role_classic).toUpperCase(),
      role_mantra: text(rec.role_mantra) || null,
      qt_a: int(rec.qt_a) ?? 0,
      qt_i: int(rec.qt_i) ?? 0,
      diff: int(rec.diff) ?? 0,
      qt_a_m: int(rec.qt_a_m),
      qt_i_m: int(rec.qt_i_m),
      diff_m: int(rec.diff_m),
      fvm: int(rec.fvm),
      fvm_m: int(rec.fvm_m),
    });
  });
  return rows;
}

const wb = new ExcelJS.Workbook();
await wb.xlsx.load(await readFile(FIXTURE));
const active = readSheet(wb.getWorksheet("Tutti"));
const activeIds = new Set(active.map((r) => r.id));
const ceded = readSheet(wb.getWorksheet("Ceduti")).filter((r) => !activeIds.has(r.id));

const cols = [
  "id",
  "name",
  "team",
  "role_classic",
  "role_mantra",
  "qt_a",
  "qt_i",
  "diff",
  "qt_a_m",
  "qt_i_m",
  "diff_m",
  "fvm",
  "fvm_m",
  "status",
  "out_of_list_at",
];
const line = (r, status) =>
  `  (${[r.id, r.name, r.team, r.role_classic, r.role_mantra, r.qt_a, r.qt_i, r.diff, r.qt_a_m, r.qt_i_m, r.diff_m, r.fvm, r.fvm_m].map(sql).join(", ")}, '${status}', ${status === "active" ? "null" : "now()"})`;

const body = [
  `-- Generated by scripts/generate-players-seed.mjs from ${path.basename(FIXTURE)}. Do not edit.`,
  `-- ${active.length} active players, ${ceded.length} out of list.`,
  `insert into public.players (${cols.join(", ")}) values`,
  [...active.map((r) => line(r, "active")), ...ceded.map((r) => line(r, "out_of_list"))].join(
    ",\n",
  ),
  `on conflict (id) do update set`,
  `  name = excluded.name, team = excluded.team, role_classic = excluded.role_classic, role_mantra = excluded.role_mantra,`,
  `  qt_a = excluded.qt_a, qt_i = excluded.qt_i, diff = excluded.diff, qt_a_m = excluded.qt_a_m, qt_i_m = excluded.qt_i_m,`,
  `  diff_m = excluded.diff_m, fvm = excluded.fvm, fvm_m = excluded.fvm_m, status = excluded.status, out_of_list_at = excluded.out_of_list_at;`,
  "",
].join("\n");

await mkdir(path.dirname(OUT), { recursive: true });
await writeFile(OUT, body);
console.log(`wrote ${OUT}: ${active.length} active, ${ceded.length} out of list`);
